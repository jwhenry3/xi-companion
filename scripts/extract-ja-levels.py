#!/usr/bin/env python3
"""Extract job-ability acquisition data from bg-wiki into
addon/xicompanion/ja_levels.lua.

res.job_abilities carries no job/level requirement, so "obtainable" for
JAs comes from scraping the {{Job Ability}} infobox on each ability's
bg-wiki page: |job= |level= |type= (Level/Merit/JP/…) and |command= (the
canonical macro line, e.g. /ja "Berserk" <me>).

  - https://www.bg-wiki.com/ffxi/Category:Job_Ability via the MediaWiki
    API — categorymembers for titles, then batched revisions content.

Output is keyed by lowercased English name (matching
res.job_abilities[].en at runtime):

  return { ['berserk'] = {job='Warrior', level=15, type='Level',
                           cmd='/ja "Berserk" <me>'}, ... }

Usage:
    python scripts/extract-ja-levels.py [--out addon/xicompanion/ja_levels.lua]
"""

import argparse
import json
import re
import sys
import urllib.parse
import urllib.request

API = 'https://www.bg-wiki.com/api.php'
UA = {'User-Agent': 'xicompanion/1.0 (ja table generator)'}
CATEGORY = 'Category:Job_Ability'
BATCH = 50  # max titles per revisions query


def get(params):
    url = API + '?' + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read())


def fetch_titles():
    titles = []
    params = {
        'action': 'query',
        'list': 'categorymembers',
        'cmtitle': CATEGORY,
        'cmlimit': '500',
        'format': 'json',
    }
    while True:
        data = get(params)
        titles += [m['title'] for m in
                   data.get('query', {}).get('categorymembers', [])
                   if m.get('ns') == 0]
        cont = data.get('continue', {}).get('cmcontinue')
        if not cont:
            break
        params['cmcontinue'] = cont
    return titles


def fetch_wikitext(titles):
    """Yields (title, wikitext) pairs, BATCH titles per request."""
    for i in range(0, len(titles), BATCH):
        data = get({
            'action': 'query',
            'prop': 'revisions',
            'rvslots': 'main',
            'rvprop': 'content',
            'titles': '|'.join(titles[i:i + BATCH]),
            'format': 'json',
        })
        for p in data.get('query', {}).get('pages', {}).values():
            revs = p.get('revisions')
            if not revs:
                continue
            yield p.get('title', ''), revs[0]['slots']['main']['*']


def param(wt, name):
    m = re.search(r'\|\s*%s\s*=\s*([^\n|}]*)' % re.escape(name), wt)
    if not m:
        return ''
    # values often carry inline comments: |level=15   <!-- Optional -->
    return re.sub(r'<!--.*?-->', '', m.group(1)).strip()


def parse(title, wt):
    if '{{Job Ability' not in wt:
        return None
    level_s = param(wt, 'level')
    # wiki markup leaks in some infoboxes: '[[SP Ability]]', '[[X|Y]]'
    typ = re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]*)\]\]', r'\1',
                 param(wt, 'type')) or 'Level'
    job = re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]*)\]\]', r'\1',
                 param(wt, 'job'))
    return {
        'job': job or None,
        'level': int(level_s) if level_s.isdigit() else None,
        'type': typ,
        'cmd': param(wt, 'command') or None,
    }


def lua_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def lua_val(v):
    if v is None:
        return 'nil'
    if isinstance(v, int):
        return str(v)
    return lua_str(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='addon/xicompanion/ja_levels.lua')
    args = ap.parse_args()

    titles = fetch_titles()
    if not titles:
        print('category empty — refusing to write', file=sys.stderr)
        return 1

    table = {}
    skipped = 0
    for title, wt in fetch_wikitext(titles):
        rec = parse(title, wt)
        if rec is None:
            skipped += 1
            continue
        key = title.strip().lower()
        if not key:
            continue
        table[key] = rec

    if not table:
        print('no records parsed — refusing to write', file=sys.stderr)
        return 1

    lines = [
        '-- Job-ability acquisition table for abilities.lua.',
        '-- Generated by scripts/extract-ja-levels.py from bg-wiki',
        '-- ' + CATEGORY + ' infoboxes — do not edit by hand.',
        '-- Keyed by lowercased res.job_abilities[].en. job is a job',
        '-- display name, level the acquisition level (nil for merit/JP),',
        '-- type is Level|Merit|JP|…, cmd the canonical macro line.',
        'return {',
    ]
    for key in sorted(table):
        r = table[key]
        fields = ', '.join('%s=%s' % (k, lua_val(v))
                           for k, v in r.items() if v is not None)
        lines.append('    [%s] = {%s},' % (lua_str(key), fields))
    lines.append('}')

    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %d abilities (%d non-JA members skipped) -> %s'
          % (len(table), skipped, args.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
