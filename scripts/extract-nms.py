#!/usr/bin/env python3
"""Extract notorious-monster names from bg-wiki into
addon/xicompanion/nm_names.lua.

The game client is never told a mob is an NM — there's no flag on the
entity struct or in widescan packets — so the radar flags them by name
instead. NM names are unique within a zone (and effectively globally),
so a name set is a reliable match.

Source:
  - https://www.bg-wiki.com/ffxi/Category:Notorious_Monster via the
    MediaWiki API (categorymembers, cmtype=page, continuation).

Page titles are normalized for matching against entity/widescan names:
parenthetical disambiguators stripped ("Foo (NM)" -> "Foo") and
everything lowercased. The generated file is a plain name set:

  return { ['valkurm emperor'] = true, ... }

Usage:
    python scripts/extract-nms.py [--out addon/xicompanion/nm_names.lua]
"""

import argparse
import json
import re
import sys
import urllib.parse
import urllib.request

API = 'https://www.bg-wiki.com/api.php'
UA = {'User-Agent': 'xicompanion/1.0 (nm table generator)'}
CATEGORY = 'Category:Notorious_Monster'


def get(params):
    url = API + '?' + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read())


def fetch_names():
    names = set()
    params = {
        'action': 'query',
        'list': 'categorymembers',
        'cmtitle': CATEGORY,
        'cmtype': 'page',
        'cmlimit': '500',
        'format': 'json',
    }
    while True:
        data = get(params)
        for m in data.get('query', {}).get('categorymembers', []):
            title = m.get('title', '')
            # strip disambiguation suffixes: "Foo (NM)", "Foo (San d'Oria)"
            name = re.sub(r'\s*\(.*\)\s*$', '', title).strip().lower()
            if name:
                names.add(name)
        cont = data.get('continue', {}).get('cmcontinue')
        if not cont:
            break
        params['cmcontinue'] = cont
    return names


def lua_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='addon/xicompanion/nm_names.lua')
    args = ap.parse_args()

    names = fetch_names()
    if not names:
        print('no names fetched — refusing to write an empty table',
              file=sys.stderr)
        return 1

    lines = [
        '-- Notorious-monster name set for map.lua NM flagging.',
        '-- Generated by scripts/extract-nms.py from bg-wiki',
        '-- ' + CATEGORY + ' — do not edit by hand.',
        '-- Keys are lowercased, disambiguation-free mob names.',
        'return {',
    ]
    for name in sorted(names):
        lines.append('    [%s] = true,' % lua_str(name))
    lines.append('}')

    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %d names -> %s' % (len(names), args.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
