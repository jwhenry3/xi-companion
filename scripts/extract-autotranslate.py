#!/usr/bin/env python3
"""Extract the client's auto-translate phrase table -> addon/xicompanion/at_names.lua

The dictionary lives in a single client DAT (file id 0xD971 = English,
0xD8F9 = Japanese — Windower ResourceExtractor's Program.cs). File ids
resolve through FTABLE.DAT at the install root:

    u16 @ id*2 -> ROM/<file/128>/<file%128>.DAT

Record format (ResourceExtractor ATParser.cs):

    u8   unused
    u8   language
    u8   id high byte
    u8   id low byte
    if (id & 0xFF) == 0:            # category header
        skip 0x20, name = 0x20 bytes (NUL-padded), skip 8
    else:
        u8 length; name = `length` bytes (last byte is a terminator)
        if language == 1: skip u8 + that many bytes

Generates at_names.lua:  return { [id] = "en name", ... }
"""

import argparse
import os
import struct
import sys

AT_EN_FID = 0xD971
DEFAULT_FFXI = r'C:\Program Files (x86)\PlayOnline\SquareEnix\FINAL FANTASY XI'


def dat_path(ffxi: str, fid: int) -> str | None:
    ft_path = os.path.join(ffxi, 'FTABLE.DAT')
    try:
        with open(ft_path, 'rb') as f:
            ft = f.read()
    except OSError:
        print(f'error: cannot read {ft_path}', file=sys.stderr)
        return None
    off = fid * 2
    if off + 2 > len(ft):
        print(f'error: fid {fid:#x} out of FTABLE range', file=sys.stderr)
        return None
    (filenum,) = struct.unpack_from('<H', ft, off)
    p = os.path.join(ffxi, 'ROM', str(filenum // 128), f'{filenum % 128}.DAT')
    return p if os.path.exists(p) else None


def parse(buf: bytes) -> dict[int, str]:
    out: dict[int, str] = {}
    i, n = 0, len(buf)
    while i < n:
        if i + 4 > n:
            break
        lang = buf[i + 1]
        fid = buf[i + 2] * 256 | buf[i + 3]
        i += 4
        if fid & 0xFF == 0:
            i += 0x20
            name_data = buf[i:i + 0x20]
            i += 0x20 + 8
            name = name_data.split(b'\x00', 1)[0]
        else:
            length = buf[i]
            i += 1
            name = buf[i:i + length - 1]
            i += length
            if lang == 1:
                pad = buf[i]
                i += 1 + pad
        out[fid] = name.decode('shift_jis', errors='replace')
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--ffxi', default=DEFAULT_FFXI)
    ap.add_argument('--out', default=os.path.join('addon', 'xicompanion', 'at_names.lua'))
    args = ap.parse_args()

    p = dat_path(args.ffxi, AT_EN_FID)
    if not p:
        print('error: could not resolve AT table DAT', file=sys.stderr)
        return 1
    print(f'{p}')

    with open(p, 'rb') as f:
        table = parse(f.read())
    print(f'{len(table)} phrases')

    lines = [
        '-- generated by scripts/extract-autotranslate.py from the client AT DAT',
        'return {',
    ]
    for fid in sorted(table):
        name = table[fid].replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'    [{fid}] = "{name}",')
    lines.append('}')
    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
