"""Extract menu spell/JA/WS icons from ROM/280/15.DAT (chunked store) and
ROM/324/95.DAT (second store: Trust fa_*, SP sp2_*, mounts, emotes).

Chunks are name-keyed: [0xa1][group:8][name:8][header][TXD\x00][payload].
Payload is packed pixel data (~1KB for 32x32) — palette/format TBD; we dump
raw index bytes as grayscale so names stay browsable in icon_dump/.

Writes:
  addon/xicompanion/menu_icon_names.lua  — { [i] = "group/name" } ordered
  icon_dump/menu_280_15/, menu_324_95/    — BMP previews
"""
import struct, os, re, sys

BASE = r"C:/Program Files (x86)/PlayOnline/SquareEnix/FINAL FANTASY XI"
OUTD = os.path.join(os.path.dirname(__file__), "..", "icon_dump")
ADDON = os.path.join(os.path.dirname(__file__), "..", "addon", "xicompanion")

def chunks(d):
    out, off = [], 0
    while off + 16 <= len(d):
        info = struct.unpack_from("<I", d, off + 4)[0]
        size = (info >> 7) * 16
        out.append((d[off:off+4], d[off+16:off+size]))
        if size <= 16: break
        off += size
    return out

def bmp(px, w, h):
    # BMP rows are stored bottom-up; DXT3 decodes top-down — flip
    rows = [px[i*w*4:(i+1)*w*4] for i in range(h)]
    px = b"".join(reversed(rows))
    return (b"BM"+struct.pack("<IHHI",122+len(px),0,0,122)
        +struct.pack("<IiiHHIIiiII",108,w,h,1,32,3,len(px),2835,2835,0,0)
        +struct.pack("<IIII",0xFF0000,0xFF00,0xFF,0xFF000000)+b"sRGB"+b"\0"*36
        +struct.pack("<III",0,0,0))+px

def _c16(v): return ((v>>11&31)*255//31,(v>>5&63)*255//63,(v&31)*255//31)

def dxt3(px, w, h):
    out = bytearray(w*h*4)
    for by in range(h//4):
        for bx in range(w//4):
            blk = px[(by*(w//4)+bx)*16:(by*(w//4)+bx)*16+16]
            a = struct.unpack("<Q", blk[:8])[0]
            c0,c1 = struct.unpack_from("<HH", blk, 8)
            C = [_c16(c0), _c16(c1)]
            C.append(tuple((2*C[0][i]+C[1][i])//3 for i in range(3)))
            C.append(tuple((C[0][i]+2*C[1][i])//3 for i in range(3)))
            ci = struct.unpack_from("<I", blk, 12)[0]
            for i in range(16):
                o = ((by*4+i//4)*w + bx*4+i%4)*4
                r,g,b = C[(ci>>(2*i))&3]
                out[o:o+4] = bytes([b,g,r,min(255,((a>>(4*i))&0xF)*34)])
    return bytes(out)

def extract(path, outdir):
    d = open(os.path.join(BASE, path), "rb").read()
    os.makedirs(outdir, exist_ok=True)
    names = []
    for tag, p in chunks(d):
        if len(p) < 0x45 or p[:1] != b"\xa1": continue
        grp = p[1:9].split(b"\x00")[0].decode("latin1").strip()
        nm = re.match(rb"[A-Za-z0-9_]+", p[9:17])
        nm = nm.group(0).decode() if nm else ""
        if not nm: continue
        w, h = struct.unpack_from("<ii", p, 0x15)
        size = struct.unpack_from("<I", p, 0x3d)[0]
        px = p[0x45:0x45+size]
        if p[0x39:0x3d] == b"3TXD":
            rgba = dxt3(px, w, h)
        else:
            rgba = bytearray()
            for b in px[:w*h]: rgba += bytes([b,b,b,255])
            rgba = bytes(rgba[:w*h*4])
        open(f"{outdir}/{len(names):03d}_{grp}_{nm}.bmp","wb").write(
            bmp(rgba, w, h))
        names.append(f"{grp}/{nm}")
    return names

def ws_tiles(path, outdir):
    """misc/ws is a 128x128 DXT3 sheet = 16 weapon-class icons (4x4 grid
    of 32x32). Slice to per-tile BMPs; index N = tile N."""
    d = open(os.path.join(BASE, path), "rb").read()
    for tag, p in chunks(d):
        if p[:1] == b"\xa1" and p[9:12] == b"ws ":
            w, h = struct.unpack_from("<ii", p, 0x15)
            size = struct.unpack_from("<I", p, 0x3d)[0]
            rgba = dxt3(p[0x45:0x45+size], w, h)
            n = 0
            for ty in range(h // 32):
                for tx in range(w // 32):
                    tile = bytearray()
                    for y in range(32):
                        row = rgba[((ty*32+y)*w + tx*32)*4:][:32*4]
                        tile += row
                    open(f"{outdir}/ws_{n}.bmp", "wb").write(
                        bmp(bytes(tile), 32, 32))
                    n += 1
            return n
    return 0

n1 = extract(r"ROM/280/15.DAT", os.path.join(OUTD, "menu_280_15"))
n2 = extract(r"ROM/324/95.DAT", os.path.join(OUTD, "menu_324_95"))
# servable copies + addon name map
MENUD = os.path.join(ADDON, "data", "menuicons")
os.makedirs(MENUD, exist_ok=True)
alln = n1 + n2
lua = "-- GENERATED by extract-menuicons.py: menu icon names (ROM/280/15 + 324/95)\nreturn {\n"
lua += "".join(f'    [{i}] = "{n}",\n' for i, n in enumerate(alln))
lua += "}\n"
open(os.path.join(ADDON, "menu_icon_names.lua"), "w").write(lua)
# copy BMPs named by index for the /api/menuicon route
import shutil
for i, full in enumerate(alln):
    g, n = full.split("/", 1)
    src_dir = "menu_280_15" if i < len(n1) else "menu_324_95"
    src = os.path.join(OUTD, src_dir, f"{i if i<len(n1) else i-len(n1):03d}_{g}_{n}.bmp")
    if os.path.exists(src):
        shutil.copy(src, os.path.join(MENUD, f"{i}.bmp"))
print("280/15:", len(n1), "| 324/95:", len(n2), "| menuicons:", len(alln))
